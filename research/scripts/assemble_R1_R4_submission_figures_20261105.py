def font(size,bold=False):
    paths=(
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
        if bold else
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/truetype/liberation2/LiberationSans-Bold.ttf"
        if bold else
        "/usr/share/fonts/truetype/liberation2/LiberationSans-Regular.ttf",
    )
    for p in paths:
        if Path(p).exists():
            return ImageFont.truetype(p,size)
    return ImageFont.load_default()


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def compose(figure, roots, output):
    name,title,panels,notes1,notes2=figure
    rendered=[]
    source=[]
    max_render_w=BODY_W
    for letter,heading,group,filename in panels:
        src=Path(roots[group])/filename
        if not src.is_file():
            raise FileNotFoundError("Missing immutable numeric plot: "+str(src))
        with Image.open(src) as im:
            # Preserve original source content; only a small proportional
            # scale-down when the original full plot exceeds figure width.
            picture=im.convert("RGB").copy()
            if picture.width>max_render_w:
                proportional=max_render_w/picture.width
                picture=picture.resize((max_render_w,
                        round(picture.height*proportional)),Image.Resampling.LANCZOS)
        rendered.append((letter,heading,picture))
        source.append(dict(figure=name,panel=letter,caption=heading,
                           source_artifact_group=group,source_file=filename,
                           original_sha256=sha(src),
                           source_original_dimensions=list(Image.open(src).size),
                           rendered_dimensions=list(picture.size)))
    # No cropping, scientific axis relabeling or reinterpretation of numeric CI.
    h=TOP_MARGIN+sum(PANEL_HEADER_H+picture.height for _,_,picture in rendered)
    h+=PANEL_GAP*(len(rendered)-1)+FOOTER_H+MARGIN
    canvas=Image.new("RGB",(CANVAS_W,h),"white")
    d=ImageDraw.Draw(canvas)
    d.text((MARGIN,40),title,font=font(TITLE_SIZE,True),fill=(15,22,29))
    d.line([(MARGIN,92),(CANVAS_W-MARGIN,92)],fill=(165,170,175),width=2)
    y=TOP_MARGIN
    for i,(letter,heading,picture) in enumerate(rendered):
        d.text((MARGIN,y+13),f"{letter}  {heading}",
               font=font(LABEL_SIZE,True),fill=(28,30,33))
        y+=PANEL_HEADER_H
        x=MARGIN+(BODY_W-picture.width)//2
        canvas.paste(picture,(x,y))
        y+=picture.height
        if i+1<len(rendered):
            y+=PANEL_GAP
    d.line([(MARGIN,y+18),(CANVAS_W-MARGIN,y+18)],
           fill=(160,165,170),width=2)
    d.text((MARGIN,y+38),notes1,font=font(NOTE_SIZE),fill=(55,55,55))
    d.text((MARGIN,y+78),notes2,font=font(NOTE_SIZE),fill=(55,55,55))
    out=Path(output)/name
    canvas.save(out,optimize=True)
    if out.stat().st_size<100000:
        raise AssertionError("Original scientific composite figure unexpectedly small")
    return source,dict(filename=out.name,width=canvas.width,height=canvas.height,
                       sha256=sha(out),panels=len(panels))


def main():
    p=argparse.ArgumentParser()
    for group in ("fig1","plant","p1","r4"):
        p.add_argument("--"+group,type=Path,required=True)
    p.add_argument("--output",type=Path,required=True)
    a=p.parse_args()
    roots={g:getattr(a,g) for g in ("fig1","plant","p1","r4")}
    a.output.mkdir(parents=True,exist_ok=True)
    sources=[]
    products=[]
    for figure in FIGURES:
        detail,summary=compose(figure,roots,a.output)
        sources.extend(detail)
        products.append(summary)
    receipt=dict(
        status="R1_R4_FOUR_SUBMISSION_FIGURES_SOURCE_ONLY_ASSEMBLY_PASS",
        panel_count=len(sources),main_figures=products,
        source_panels=sources,
        input_original_numeric_panels_preserved_without_data_recomputation=True,
        original_figure_count=4,
        assembled_submission_figures_not_independent_field_validation=True,
        observational_and_simulation_inference_distinct=True,
        note="Visual assembly of source-verified numerical figures only; captions in manuscript."
    )
    (a.output/"R1_R4_submitted_figure_source_receipt.json").write_text(
        json.dumps(receipt,indent=2,ensure_ascii=False)+"\n",encoding="utf-8")
    print("R1_R4_FOUR_SOURCE_BACKED_FIGURES_ASSEMBLED",json.dumps({
        k:v for k,v in receipt.items() if k!="source_panels"},ensure_ascii=False),flush=True)


if __name__=="__main__":
    main()
