def scenario_set(inventory: pd.DataFrame, levels=LEVELS):
    groups=inventory[inventory.context.isin(CONTEXTS)&
                     inventory.family.isin(FAMILIES)&
                     inventory.edge.isin(EDGES)].sort_values("case")
    if len(groups)!=24 or groups.case.duplicated().any():
        raise ValueError("24 structural cases required")
    if len(groups.groupby(["context","family","risk","edge"]))!=24:
        raise ValueError("Structure factorial is incomplete")
    axes=np.linspace(.25,2.,levels)
    records=[]
    for row in groups.to_dict("records"):
        for v,s,d in itertools.product((0.,1.),axes,axes):
            records.append(dict(**row,vegetation=v,S_source=s,D_source=d))
    return pd.DataFrame(records),groups


def prior_draws(n=DRAW_COUNT,seed=SEED):
    if n<2 or n%2:
        raise ValueError("Even prior-draw count >=2 required for balanced maturity delays")
    from scipy.stats.qmc import LatinHypercube
    u=LatinHypercube(d=7,seed=seed).random(n)
    # Declared exploratory, intentionally NOT empirically calibrated priors.
    def linear(v,a,b):return a+(b-a)*v
    records=[]
    delays=np.tile(np.asarray(REF_F_DELAY,int),n//2)
    delays=delays[np.random.default_rng(seed+1).permutation(n)]
    for i,a in enumerate(u):
        records.append(dict(draw=i,attack_scale=float(np.exp(np.log(ATTACK_MIN)+
                       a[0]*(np.log(ATTACK_MAX)-np.log(ATTACK_MIN)))),
                       s_growth_multiplier=float(linear(a[1],*GROWTH_FACTOR_RANGE)),
                       d_growth_multiplier=float(linear(a[2],*GROWTH_FACTOR_RANGE)),
                       rho=float(linear(a[3],*RHO_RANGE)),
                       conversion=float(linear(a[4],*CONVERSION_RANGE)),
                       f_juvenile_survival=float(linear(a[5],*F_JUV_RANGE)),
                       f_adult_survival=float(linear(a[6],*F_ADULT_RANGE)),
                       f_delay=int(delays[i]),prior_label="ILLUSTRATIVE_LHS_NOT_LITERATURE_CALIBRATED"))
    return pd.DataFrame(records)


def anchor_values():
    return dict(draw=-1,attack_scale=.5,s_growth_multiplier=1.,d_growth_multiplier=1.,
                rho=.75,conversion=4.,f_juvenile_survival=.8,
                f_adult_survival=.4,f_delay=2,
                prior_label="FIXED_OCT29_ARCHIVE_REPLAY_ONLY")


def batch_simulate(grid, params, years=COHORT_YEARS, window=WINDOW, dt=DT):
    """True paired source-grounded recurrence; per-draw risk batches."""
    if not (1<=window<=years) or len(grid)==0:
        raise ValueError("Invalid source grid or horizon")
    frames=[]
    for risk,g in grid.groupby("risk",sort=True):
        g=g.reset_index(drop=True)
        size=len(g)
        scenarios=[dict(community="FSD",roles=15,refuge_order="D",
                        vegetation=float(r.vegetation),f_arrival=20.,
                        s_arrival=float(r.sa),d_arrival=float(r.da),
                        attack_scale=float(params["attack_scale"]),cue=0.,
                        reverse=r.edge=="frog_reverse",
                        rho=float(params["rho"])) for r in g.itertuples(index=False)]
        controls=dict(cover_SF=1.,cover_DF=0.,cover_DS=0.,cover_SD=0.,
                      support_DF=0.,support_DS=0.,emerge_survival=0.,
                      emerge_exposure=0.,cue_SD=0.,edge_SD=np.ones(size),
                      edge_DS=np.ones(size))
        options=dict(stage_durations=np.column_stack(
                         [np.full(size,45.),np.full(size,80.),g.dduration.to_numpy(float)]),
                     functional_response="litter",behavioral_refuge=bool(risk),
                     handling_s=g.hs.to_numpy(float),handling_d=g.hd.to_numpy(float),
                     s_growth=g.sg.to_numpy(float)*float(params["s_growth_multiplier"]),
                     d_growth=g.dg.to_numpy(float)*float(params["d_growth_multiplier"]),
                     sd_size_mode="dynamic",pathway_controls=controls)
        source=np.column_stack([np.ones(size),g.S_source.to_numpy(float),
                                g.D_source.to_numpy(float)])
        f_surv=float(params["f_adult_survival"])
        f_juvenile=float(params["f_juvenile_survival"])
        conv=float(params["conversion"])
        out=summarize_years(
            scenarios,years=years,window=window,dt=dt,source_cohorts=source,
            seasonal_options=options,
            conversion=(conv,conv,conv),survival=(f_surv,.5,0.),
            juvenile=(f_juvenile,.8,.8),
            delays=(int(params["f_delay"]),2,1))
        if not np.isfinite(out[["F_B","F_fraction","F_B_sd"]].to_numpy(float)).all():
            raise AssertionError("Nonfinite demographic output")
        if (out.F_B<=0).any() or (out.F_fraction<0).any() or (out.F_fraction>1+1e-10).any():
            raise AssertionError("Invalid frog demographic output")
        frames.append(pd.concat([g,out],axis=1))
    result=pd.concat(frames,ignore_index=True)
    if len(result)!=len(grid):raise AssertionError("Incomplete simulated grid")
    return result


def validate_archive_anchor(grid,archived,atol=1e-8):
    actual=batch_simulate(grid,anchor_values())
    sources=pd.concat(archived,ignore_index=True)
    key=["case","vegetation","S_source","D_source"]
    a=actual.sort_values(key).reset_index(drop=True)
    b=sources[sources.case.isin(a.case.unique())].sort_values(key).reset_index(drop=True)
    if len(a)!=len(b) or not np.allclose(a[key].to_numpy(float),b[key].to_numpy(float),
                                         rtol=0,atol=1e-9):
        raise AssertionError("Archived fixed-case source coordinate mismatch")
    error={}
    for col in ("F_B","F_fraction","F_B_sd"):
        value=float(np.abs(a[col].to_numpy(float)-b[col].to_numpy(float)).max())
        error[col]=value
        if value>atol:raise AssertionError("Unchanged baseline mismatch "+col+": "+str(value))
    return error


def as_surface(records, levels=LEVELS):
    out={}
    coords=np.asarray([(v,s,o) for v in (0.,1.) for s in np.linspace(.25,2.,levels)
                       for o in np.linspace(.25,2.,levels)])
    for case,g in records.groupby("case"):
        g=g.sort_values(["vegetation","S_source","D_source"])
        if len(g)!=len(coords) or not np.allclose(
            g[["vegetation","S_source","D_source"]].to_numpy(float),coords,rtol=0,atol=1e-9):
            raise ValueError("Simulator grid lacks stage density cells")
        out[f"case_{int(case):03d}"]=g.F_B.to_numpy(float).reshape(2,levels,levels)
    if len(out)!=24:raise AssertionError("Incomplete 24 structural cases")
    return out


def family_name(row):
    return "|".join([str(row["context"]),str(row["family"]),
                     "risk" if bool(row["risk"]) else "no_risk"])


def score_rate_library(library,observed_by_bg,quantiles_by_bg):
    records=[]
    for bg,obs in observed_by_bg.items():
        sub=library[library.background==bg]
        for r in sub.to_dict("records"):
            lo,hi=quantiles_by_bg[bg]
            match=sum(lo[i]<=r[PATTERNS[i]]<=hi[i] for i in range(len(PATTERNS)))
            records.append(dict(background=bg,draw=int(r["draw"]),case=r["case"],
                                family=r["family"],context=r["context"],risk=r["risk"],
                                edge=r["edge"],structural_group=r["structural_group"],
                                distance=float(r["distance"]),fitted_patterns_within_95=int(match),
                                heldout_patterns_within_95=int(r["heldout_patterns_within_95"])))
    return pd.DataFrame(records)


def pseudo_recovery(library, inv_by_bg, group_labels, n_draws):
    """Leave-one-*actual process rate draw*-out, no same-draw leakage."""
    rows=[]
    for bg in BACKGROUNDS:
        allref=library[library.background==bg]
        inv=inv_by_bg[bg]
        for draw in range(n_draws):
            training=allref[allref.draw!=draw]
            target=allref[allref.draw==draw]
            if len(training)!=(n_draws-1)*24 or len(target)!=24:
                raise AssertionError("Rate-draw holdout split invalid")
            x=training[list(PATTERNS)].to_numpy(float)
            labs=training.structural_group.to_numpy(str)
            for item in target.itertuples(index=False):
                y=np.array([getattr(item,p) for p in PATTERNS])
                delta=x-y
                d2=np.einsum("ij,jk,ik->i",delta,inv,delta)
                nearest=labs[np.argmin(d2)]
                rows.append(dict(background=bg,heldout_draw=draw,
                                 case=item.case,true_group=item.structural_group,
                                 nearest_group=nearest,group_recovered=bool(nearest==item.structural_group),
                                 minimum_distance=float(np.sqrt(d2.min()))))
    return pd.DataFrame(rows)


def evaluate(draws,grid,sites,archived):
    checks=validate_archive_anchor(grid,archived)
    observed={};inv={};limits={};group_map={};
    for case,g in grid.groupby("case"):
        group_map[f"case_{int(case):03d}"]=family_name(g.iloc[0])
    for bg in BACKGROUNDS:
        design=get_design(sites,bg)
        vec,hold=stats_from_y(sites.strong_rate,design,holdout=True)
        compare_frozen_macro(vec,bg)
        reps,cov,invc,info=bootstrap_observed(sites.strong_rate,design,
                                              sites.spatial_block,n_boot=999)
        observed[bg]=dict(stats=vec,hold=hold,design=design,reps=reps)
        inv[bg]=invc
        limits[bg]=np.quantile(reps,[.025,.975],axis=0)
    records=[];cells=[]
    for row in draws.to_dict("records"):
        sim=batch_simulate(grid,row)
        sim["draw"]=int(row["draw"])
        cells.append(sim[["draw","case","vegetation","S_source","D_source",
                          "F_B","F_fraction","F_B_sd"]])
        surfaces=as_surface(sim)
        for bg in BACKGROUNDS:
            ref=observed[bg]
            assessment=pattern_assessment(sites,bg,ref["design"],surfaces,
                                           ref["stats"],ref["hold"],inv[bg],ref["reps"])
            for a in assessment.to_dict("records"):
                key=a["case"]
                records.append(dict(background=bg,draw=int(row["draw"]),
                                    case=key,structural_group=group_map[key],
                                    context=grid.loc[grid.case==int(key.split("_")[1]),"context"].iloc[0],
                                    family=grid.loc[grid.case==int(key.split("_")[1]),"family"].iloc[0],
                                    edge=grid.loc[grid.case==int(key.split("_")[1]),"edge"].iloc[0],
                                    risk=bool(grid.loc[grid.case==int(key.split("_")[1]),"risk"].iloc[0]),
                                    distance=float(a["distance_mahalanobis"]),
                                    heldout_patterns_within_95=-1,
                                    **{p:float(a["model_"+p]) for p in PATTERNS},
                                    **{("heldout_"+p):float(a["model_holdout_"+p])
                                       for p in HOLDOUT}))
        print("TRUE PROCESS SIM",int(row["draw"]),"rate values",json.dumps(row,default=str),
              "candidate-background rows",len(records),flush=True)
    lib=pd.DataFrame(records)
    if len(lib)!=len(draws)*24*2:raise AssertionError("Incorrect rate-library candidate count")
    # Add true unused-pattern interval checks, from observed-only bootstrap
    # statistics, by reusing same-site observations (never used to choose prior).
    from pattern_oriented_abc_pilot import bootstrap_heldout
    for bg in BACKGROUNDS:
        observed_h=bootstrap_heldout(sites.strong_rate,observed[bg]["design"],
                                    sites.spatial_block,n_boot=999)
        lo,hi=np.quantile(observed_h,[.025,.975],axis=0)
        mask=lib.background==bg
        array=lib.loc[mask,["heldout_"+p for p in HOLDOUT]].to_numpy(float)
        lib.loc[mask,"heldout_patterns_within_95"]=np.sum((array>=lo)&(array<=hi),axis=1)
    scores=score_rate_library(lib,observed,limits)
    recovered=pseudo_recovery(lib,inv,group_map,len(draws))
    mass=[];select=[]
    for bg in BACKGROUNDS:
        part=lib[lib.background==bg].sort_values(["distance","case","draw"]).copy()
        n=max(1,int(np.ceil(len(part)*ABC_FRACTION)))
        accepted=part.head(n)
        grp=part.groupby("structural_group").size()
        counts=accepted.groupby("structural_group").size().reindex(grp.index,fill_value=0)
        weights=(counts/grp).astype(float)
        weights/=weights.sum()
        for group,prob in weights.items():
            mass.append(dict(background=bg,structural_group=group,
                             illustrative_acceptance_share=float(prob),
                             accepted_count=int(counts[group]),
                             available_prior_draws=int(grp[group]),
                             status="MODEL_RERUN_WITH_EXPLORATORY_UNCALIBRATED_RATE_RANGES"))
        best=part.iloc[0]
        select.append(dict(background=bg,best_case=best.case,best_group=best.structural_group,
                           best_rate_draw=int(best.draw),best_distance=float(best.distance),
                           best_fitted_patterns=int(scores[(scores.background==bg)&
                           (scores.case==best.case)&(scores.draw==best.draw)].fitted_patterns_within_95.iloc[0]),
                           best_heldout_patterns=int(best.heldout_patterns_within_95),
                           n_full_six_pattern_fit=int((scores[(scores.background==bg)].
                                                     fitted_patterns_within_95==6).sum()),
                           n_evaluated=len(part),pseudo_recovery_group_rate=float(
                               recovered[recovered.background==bg].group_recovered.mean()),
                           status="EXPLORATORY_RATE_PRIOR_PREDICTIVE_NOT_FIELD_CAUSAL"))
    return dict(source_replay_errors=checks,library=lib,cell_library=pd.concat(cells,ignore_index=True),
                scores=scores,recovery=recovered,acceptance=pd.DataFrame(mass),
                summary=pd.DataFrame(select))


def run(n_draws=DRAW_COUNT,save=OUT):
    save.mkdir(parents=True,exist_ok=True)
    inventory=pd.read_csv(DESIGN)
    grid,structures=scenario_set(inventory)
    sources=[pd.read_csv(p) for p in SOURCES]
    sites=load_cohort(pd.read_csv(SITE),pd.read_csv(VISITS),expected=4248)
    if int(sites.n.sum())!=63180 or int(sites.V.sum())!=506:
        raise AssertionError("Frozen NAAMP sample changed")
    draws=prior_draws(n_draws)
    data=evaluate(draws,grid,sites,sources)
    draws.to_csv(save/"hypothetical_process_rate_draws.csv",index=False)
    data["library"].to_csv(save/"process_prior_predictive_patterns.csv",index=False)
    data["scores"].to_csv(save/"process_prior_predictive_scores.csv",index=False)
    data["cell_library"].to_csv(save/"real_simulator_F_B_cells.csv.gz",index=False,
                                compression={"method":"gzip","mtime":0})
    data["recovery"].to_csv(save/"heldout_rate_draw_group_recovery.csv",index=False)
    data["acceptance"].to_csv(save/"conditional_rate_prior_acceptance.csv",index=False)
    data["summary"].to_csv(save/"process_prior_summary.csv",index=False)
    note=dict(status="REAL_SIMULATOR_EXPLORATORY_PROCESS_PRIORS_NOT_EMPIRICAL_RATE_POSTERIOR",
              n_draws=n_draws,structures=24,years=COHORT_YEARS,window=WINDOW,dt=DT,
              site_count=len(sites),visits=int(sites.n.sum()),
              model_original_replayed=True,baseline_error=data["source_replay_errors"],
              rate_prior_calibrated_from_field=False,probability_of_true_mechanism_estimated=False,
              fact="Each drawn parameter vector ran 80 years of the original seasonal+annual kernel",
              priors={"attack_scale_loguniform":[ATTACK_MIN,ATTACK_MAX],
                      "S_growth_mult_uniform":list(GROWTH_FACTOR_RANGE),
                      "D_growth_mult_uniform":list(GROWTH_FACTOR_RANGE),
                      "rho_uniform":list(RHO_RANGE),
                      "conversion_uniform":list(CONVERSION_RANGE),
                      "F_juvenile_survival_uniform":list(F_JUV_RANGE),
                      "F_adult_survival_uniform":list(F_ADULT_RANGE),
                      "F_maturation_years":list(REF_F_DELAY)},
              source_hashes={str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest()
                             for p in [SITE,VISITS,DESIGN,*SOURCES]},
              script_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest())
    (save/"receipt.json").write_text(json.dumps(note,indent=2,ensure_ascii=False)+"\n")
    print("BASELINE REPLAY "+json.dumps(data["source_replay_errors"]),flush=True)
    print("PROCESS PRIOR SUMMARY\n"+data["summary"].to_string(index=False),flush=True)
    print("CONDITIONAL HYPOTHETICAL RATE ACCEPTANCE\n"+
          data["acceptance"].sort_values(["background","illustrative_acceptance_share"],
                                         ascending=[True,False]).to_string(index=False),flush=True)
    return data


